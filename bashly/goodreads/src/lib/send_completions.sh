## [@bashly-upgrade completions send_completions]
send_completions() {
  echo $'# goodreads completion                                     -*- shell-script -*-'
  echo $''
  echo $'# This bash completions script was generated by'
  echo $'# completely (https://github.com/dannyben/completely)'
  echo $'# Modifying it manually is not recommended'
  echo $''
  echo $'_goodreads_completions_filter() {'
  echo $'  local words="$1"'
  echo $'  local cur=${COMP_WORDS[COMP_CWORD]}'
  echo $'  local result=()'
  echo $''
  echo $'  if [[ "${cur:0:1}" == "-" ]]; then'
  echo $'    echo "$words"'
  echo $''
  echo $'  else'
  echo $'    for word in $words; do'
  echo $'      [[ "${word:0:1}" != "-" ]] && result+=("$word")'
  echo $'    done'
  echo $''
  echo $'    echo "${result[*]}"'
  echo $''
  echo $'  fi'
  echo $'}'
  echo $''
  echo $'_goodreads_completions() {'
  echo $'  local cur=${COMP_WORDS[COMP_CWORD]}'
  echo $'  local compwords=("${COMP_WORDS[@]:1:$COMP_CWORD-1}")'
  echo $'  local compline="${compwords[*]}"'
  echo $''
  echo $'  case "$compline" in'
  echo $'    *\'blogs challenge\'*)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_goodreads_completions_filter "--auto --help --no --yes -a -h -n -y")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    *\'books update\'*)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_goodreads_completions_filter "--all --help -a -h")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    *\'blogs delete\'*)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_goodreads_completions_filter "--all --help -a -h")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    *\'books delete\'*)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_goodreads_completions_filter "--all --help -a -h")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    *\'blogs update\'*)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_goodreads_completions_filter "--all --help -a -h")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    *\'auth logout\'*)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_goodreads_completions_filter "--help -h")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    *\'auth switch\'*)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_goodreads_completions_filter "--help -h")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    *\'auth status\'*)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_goodreads_completions_filter "--help -h")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    *\'auth import\'*)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_goodreads_completions_filter "--help -h")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    *\'completions\'*)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_goodreads_completions_filter "--help -h bash")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    *\'blogs list\'*)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_goodreads_completions_filter "$(ls "${GOODREADS_DATA:-$HOME/.goodreads}/blogs" 2>/dev/null | sed "s/\.json$//") --all --help --limit --reverse --since --until -a -h -l -r -s -u")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    *\'books list\'*)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_goodreads_completions_filter "$(ls "${GOODREADS_DATA:-$HOME/.goodreads}/books" 2>/dev/null | sed "s/\.json$//") --help --limit -h -l")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    *\'books get\'*)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_goodreads_completions_filter "--help --json -J -h")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    *\'auth list\'*)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_goodreads_completions_filter "--help -h")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    *\'blogs get\'*)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_goodreads_completions_filter "--help --json -J -h")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    *\'books ls\'*)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_goodreads_completions_filter "$(ls "${GOODREADS_DATA:-$HOME/.goodreads}/books" 2>/dev/null | sed "s/\.json$//") --help --limit -h -l")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    *\'books rm\'*)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_goodreads_completions_filter "--all --help -a -h")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    *\'blogs rm\'*)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_goodreads_completions_filter "--all --help -a -h")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    *\'blogs ls\'*)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_goodreads_completions_filter "$(ls "${GOODREADS_DATA:-$HOME/.goodreads}/blogs" 2>/dev/null | sed "s/\.json$//") --all --help --limit --reverse --since --until -a -h -l -r -s -u")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    *\'auth ls\'*)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_goodreads_completions_filter "--help -h")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    *\'books\'*)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_goodreads_completions_filter "--help -h delete get list ls rm update")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    *\'blogs\'*)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_goodreads_completions_filter "--help -h challenge delete get list ls rm update")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    *\'auth\'*)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_goodreads_completions_filter "--help -h import list logout ls status switch")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'    *)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "$(_goodreads_completions_filter "--data-path --help --offline --version -h -v auth blogs books completions")" -- "$cur")'
  echo $'      ;;'
  echo $''
  echo $'  esac'
  echo $'} &&'
  echo $'  complete -F _goodreads_completions goodreads'
  echo $''
  echo $'# ex: filetype=sh'
}