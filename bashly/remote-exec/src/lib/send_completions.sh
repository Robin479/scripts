## [@bashly-upgrade completions send_completions]
send_completions() {
  echo $'# remote-exec completion                                   -*- shell-script -*-'
  echo $''
  echo $'# This bash completions script was generated by'
  echo $'# completely (https://github.com/bashly-framework/completely)'
  echo $'# Modifying it manually is not recommended'
  echo $''
  echo $'_remote-exec_completions_node_flag_state() {'
  echo $'  case "$1:$2" in'
  echo $'    0:--host) return 2 ;;'
  echo $'    0:--root) return 2 ;;'
  echo $'    0:--help|0:-h) return 0 ;;'
  echo $'    0:--version|0:-v) return 0 ;;'
  echo $'    0:--dry-run|0:-n) return 0 ;;'
  echo $'    1:--host) return 2 ;;'
  echo $'    1:--root) return 2 ;;'
  echo $'    1:--dry-run|1:-n) return 0 ;;'
  echo $'    1:--help|1:-h) return 0 ;;'
  echo $'    2:--host) return 2 ;;'
  echo $'    2:--root) return 2 ;;'
  echo $'    2:--dry-run|2:-n) return 0 ;;'
  echo $'    2:--help|2:-h) return 0 ;;'
  echo $'    3:--host) return 2 ;;'
  echo $'    3:--root) return 2 ;;'
  echo $'    3:--dry-run|3:-n) return 0 ;;'
  echo $'    3:--help|3:-h) return 0 ;;'
  echo $'    4:--host) return 2 ;;'
  echo $'    4:--root) return 2 ;;'
  echo $'    4:--dry-run|4:-n) return 0 ;;'
  echo $'    4:--help|4:-h) return 0 ;;'
  echo $'  esac'
  echo $''
  echo $'  return 1'
  echo $'}'
  echo $''
  echo $'_remote-exec_completions_option_seen() {'
  echo $'  local completed_option option_name'
  echo $'  for completed_option in "${completed_options[@]}"; do'
  echo $'    for option_name in "$@"; do'
  echo $'      [[ "$completed_option" == "$option_name" ]] && return 0'
  echo $'    done'
  echo $'  done'
  echo $''
  echo $'  return 1'
  echo $'}'
  echo $''
  echo $'_remote-exec_completions_resolve_node() {'
  echo $'  node_id=0'
  echo $'  node_word_count=0'
  echo $'  positional_index=0'
  echo $''
  echo $'  local word'
  echo $'  for word in "${non_options[@]}"; do'
  echo $'    case "$node_id:$word" in'
  echo $'      0:completions)'
  echo $'        node_id=1'
  echo $'        node_word_count=1'
  echo $'        ;;'
  echo $'      0:mvn)'
  echo $'        node_id=2'
  echo $'        node_word_count=1'
  echo $'        ;;'
  echo $'      0:exec)'
  echo $'        node_id=3'
  echo $'        node_word_count=1'
  echo $'        ;;'
  echo $'      0:clean)'
  echo $'        node_id=4'
  echo $'        node_word_count=1'
  echo $'        ;;'
  echo $'      *)'
  echo $'        break'
  echo $'        ;;'
  echo $'    esac'
  echo $'  done'
  echo $''
  echo $'  positional_index=$((${#non_options[@]} - node_word_count))'
  echo $'}'
  echo $''
  echo $'_remote-exec_completions() {'
  echo $'  local cur=${COMP_WORDS[COMP_CWORD]}'
  echo $'  local prev='
  echo $'  if ((COMP_CWORD > 0)); then'
  echo $'    prev=${COMP_WORDS[$((COMP_CWORD - 1))]}'
  echo $'  fi'
  echo $''
  echo $'  local completed=()'
  echo $'  if ((COMP_CWORD > 1)); then'
  echo $'    completed=("${COMP_WORDS[@]:1:$((COMP_CWORD - 1))}")'
  echo $'  fi'
  echo $''
  echo $'  local non_options=()'
  echo $'  local completed_options=()'
  echo $'  local node_id='
  echo $'  local node_word_count=-1'
  echo $'  local positional_index=0'
  echo $'  local invalid_completion=0'
  echo $'  local flag_state=0'
  echo $'  _remote-exec_completions_resolve_node'
  echo $''
  echo $'  local skip_next=0'
  echo $'  for word in "${completed[@]}"; do'
  echo $'    if ((skip_next)); then'
  echo $'      skip_next=0'
  echo $'      continue'
  echo $'    fi'
  echo $''
  echo $'    if [[ "${word:0:1}" == "-" ]]; then'
  echo $'      _remote-exec_completions_node_flag_state "$node_id" "$word"'
  echo $'      flag_state=$?'
  echo $'      if (( flag_state == 1 )); then'
  echo $'        invalid_completion=1'
  echo $'        break'
  echo $'      fi'
  echo $''
  echo $'      completed_options+=("$word")'
  echo $'      if (( flag_state == 2 )); then'
  echo $'        skip_next=1'
  echo $'      fi'
  echo $'      continue'
  echo $'    fi'
  echo $''
  echo $'    non_options+=("$word")'
  echo $'    _remote-exec_completions_resolve_node'
  echo $'  done'
  echo $''
  echo $'  COMPREPLY=()'
  echo $'  (( invalid_completion )) && return'
  echo $''
  echo $'  case "$node_id:$prev" in'
  echo $'    0:--host)'
  echo $'      return'
  echo $'      ;;'
  echo $'    0:--root)'
  echo $'      return'
  echo $'      ;;'
  echo $'    1:--host)'
  echo $'      return'
  echo $'      ;;'
  echo $'    1:--root)'
  echo $'      return'
  echo $'      ;;'
  echo $'    2:--host)'
  echo $'      return'
  echo $'      ;;'
  echo $'    2:--root)'
  echo $'      return'
  echo $'      ;;'
  echo $'    3:--host)'
  echo $'      return'
  echo $'      ;;'
  echo $'    3:--root)'
  echo $'      return'
  echo $'      ;;'
  echo $'    4:--host)'
  echo $'      return'
  echo $'      ;;'
  echo $'    4:--root)'
  echo $'      return'
  echo $'      ;;'
  echo $'  esac'
  echo $''
  echo $'  if [[ "${cur:0:1}" != "-" ]] && (( positional_index == 0 )); then'
  echo $'    case "$node_id" in'
  echo $'      0)'
  echo $'        while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "completions mvn exec clean" -- "$cur")'
  echo $'        return'
  echo $'        ;;'
  echo $'    esac'
  echo $'  fi'
  echo $''
  echo $'  if [[ "${cur:0:1}" == "-" ]]; then'
  echo $'    case "$node_id" in'
  echo $'      0)'
  echo $'        local words=()'
  echo $'        _remote-exec_completions_option_seen "--help" "-h" || words+=("--help" "-h")'
  echo $'        _remote-exec_completions_option_seen "--version" "-v" || words+=("--version" "-v")'
  echo $'        _remote-exec_completions_option_seen "--host" || words+=("--host")'
  echo $'        _remote-exec_completions_option_seen "--root" || words+=("--root")'
  echo $'        _remote-exec_completions_option_seen "--dry-run" "-n" || words+=("--dry-run" "-n")'
  echo $'        while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "${words[*]}" -- "$cur")'
  echo $'        return'
  echo $'        ;;'
  echo $'      1)'
  echo $'        local words=()'
  echo $'        _remote-exec_completions_option_seen "--host" || words+=("--host")'
  echo $'        _remote-exec_completions_option_seen "--root" || words+=("--root")'
  echo $'        _remote-exec_completions_option_seen "--dry-run" "-n" || words+=("--dry-run" "-n")'
  echo $'        _remote-exec_completions_option_seen "--help" "-h" || words+=("--help" "-h")'
  echo $'        while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "${words[*]}" -- "$cur")'
  echo $'        return'
  echo $'        ;;'
  echo $'      2)'
  echo $'        local words=()'
  echo $'        _remote-exec_completions_option_seen "--host" || words+=("--host")'
  echo $'        _remote-exec_completions_option_seen "--root" || words+=("--root")'
  echo $'        _remote-exec_completions_option_seen "--dry-run" "-n" || words+=("--dry-run" "-n")'
  echo $'        _remote-exec_completions_option_seen "--help" "-h" || words+=("--help" "-h")'
  echo $'        while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "${words[*]}" -- "$cur")'
  echo $'        return'
  echo $'        ;;'
  echo $'      3)'
  echo $'        local words=()'
  echo $'        _remote-exec_completions_option_seen "--host" || words+=("--host")'
  echo $'        _remote-exec_completions_option_seen "--root" || words+=("--root")'
  echo $'        _remote-exec_completions_option_seen "--dry-run" "-n" || words+=("--dry-run" "-n")'
  echo $'        _remote-exec_completions_option_seen "--help" "-h" || words+=("--help" "-h")'
  echo $'        while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "${words[*]}" -- "$cur")'
  echo $'        return'
  echo $'        ;;'
  echo $'      4)'
  echo $'        local words=()'
  echo $'        _remote-exec_completions_option_seen "--host" || words+=("--host")'
  echo $'        _remote-exec_completions_option_seen "--root" || words+=("--root")'
  echo $'        _remote-exec_completions_option_seen "--dry-run" "-n" || words+=("--dry-run" "-n")'
  echo $'        _remote-exec_completions_option_seen "--help" "-h" || words+=("--help" "-h")'
  echo $'        while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "${words[*]}" -- "$cur")'
  echo $'        return'
  echo $'        ;;'
  echo $'    esac'
  echo $'  fi'
  echo $''
  echo $'  case "$node_id:$positional_index" in'
  echo $'    1:0)'
  echo $'      while read -r; do COMPREPLY+=("$REPLY"); done < <(compgen -W "bash" -- "$cur")'
  echo $'      return'
  echo $'      ;;'
  echo $'  esac'
  echo $'} &&'
  echo $'  complete -F _remote-exec_completions remote-exec'
  echo $''
  echo $'# ex: filetype=sh'
}